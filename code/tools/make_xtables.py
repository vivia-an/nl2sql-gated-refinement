def xr(k):
    return "\\xres{%s}" % k


def rr(k):
    return "\\res{%s}" % k


def cell(k, d2=False, ci=True):
    s = k + (".d2" if d2 else "")
    out = xr(s)
    if ci:
        out += " " + xr(k + ".ci" + (".d2" if d2 else ""))
    return out


def colspec(cols):
    tot = float(sum(w for _, w in cols))
    return "".join("%s{%.3f}" % (k, w * len(cols) / tot) for k, w in cols)


def tabular(cols, header, rows, width="\\linewidth"):
    out = ["\\begin{tabularx}{%s}{%s}" % (width, colspec(cols)), "\\toprule", header + " \\\\", "\\midrule"]
    for r in rows:
        if r.startswith("\\midrule") or r.startswith("\\multicolumn"):
            out.append(r + (" \\\\" if r.startswith("\\multicolumn") else ""))
        else:
            out.append(r + " \\\\")
    out += ["\\bottomrule", "\\end{tabularx}"]
    return out


def float_wrap(label, caption, blocks, note):
    """One table float with one caption: the blocks (tabularx) stacked under it, then the note.  Tables taller than a page use split_table instead."""
    out = ["% GENERATED by code/tools/make_xtables.py from results/{robust,diag,ext1,pf}/*.json -- do not edit", "\\begin{table}[!htb]",
           (("\\caption{%s}\\label{%s}" % (caption, label)) if label else ("\\caption{%s}" % caption)), "\\centering", "\\footnotesize"]
    for i, b in enumerate(blocks):
        if i:
            out.append("\\vspace{4pt}")
        out += b
    if note:
        out.append("\\tabfoot{%s}" % note)
    out.append("\\end{table}")
    return "\n".join(out) + "\n"


LC_NAMES = "abcdefghijklmnop"


def long_colspec(cols, base="\\linewidth"):
    """tabularx column weights -> fixed-width p columns (longtable has no X columns and cannot take a \\dimexpr inside p{}): one length per column, \\LCa, \\LCb, ...,
    set before the table to its share of the width left after the 2N column paddings"""
    tot = float(sum(w for _, w in cols))
    spec, setl = [], []
    for i, (k, w) in enumerate(cols):
        nm = "\\LC" + LC_NAMES[i]
        al = "\\raggedleft" if k == "Z" else "\\raggedright"
        spec.append(">{%s\\arraybackslash}p{%s}" % (al, nm))
        setl.append("\\setlength{%s}{\\dimexpr(%s-%d\\tabcolsep)*%d/10000\\relax}" % (nm, base, 2 * len(cols), int(round(10000.0 * w / tot))))
    return "".join(spec), setl


def longtabular(cols, header, rows, wide_=True, tcs=None):
    """One longtable (breaks between rows, header repeated on every page, no caption of its own).  wide_: MDPI full-width environment around it.
    tcs: optional column padding (e.g. "3pt") for this table only; the column lengths are computed from it, so a narrow column keeps room for its header word (typesetting only)."""
    spec, setl = long_colspec(cols, "(\\textwidth+\\extralength)" if wide_ else "\\linewidth")
    head = ["\\toprule", header + " \\\\", "\\midrule"]
    body = setl + ["\\begin{longtable}{%s}" % spec] + head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot", "\\bottomrule", "\\endlastfoot"]
    for r in rows:
        body.append(r + (" \\\\" if not r.startswith("\\midrule") else ""))
    body.append("\\end{longtable}\\addtocounter{table}{-1}")   # the longtable environment steps the table counter once: undo, so the one \\captionof carries the number
    pad = ["\\setlength{\\tabcolsep}{%s}" % tcs] if tcs else []
    if wide_:
        # longtable ignores the margins that adjustwidth sets: shift it by \LTleft instead (full-width block: 17.5 cm, into the left margin column)
        return ["\\begingroup\\setlength{\\LTleft}{-\\extralength}\\setlength{\\LTright}{0pt}"] + pad + body + ["\\endgroup"]
    return (["\\begingroup"] + pad + body + ["\\endgroup"]) if tcs else body


def split_table(label, caption, blocks, note, clear=True):
    """A table that is taller than a page (round 3, R3 N-m10): ONE caption (\\captionof, not a float), then the blocks as page material; the long block is a longtable that breaks between rows
    and repeats its header row on every page.  The old layout was one float per part with a 'Continued.' caption each, which left half-empty pages (a float that does not fit the rest of a page
    moves to the next one)."""
    out = ["% GENERATED by code/tools/make_xtables.py from results/{robust,diag,ext1,pf}/*.json -- do not edit",
           "".join("\\ifdefined\\LC%s\\else\\newlength{\\LC%s}\\fi" % (c, c) for c in LC_NAMES[:10]),
           ("\\clearpage" if clear else "\\par\\addvspace{10pt}") + "\\begingroup\\footnotesize\\noindent\\captionof{table}{%s}\\label{%s}\\par\\nopagebreak\\vspace{2pt}" % (caption, label)]
    for i, b in enumerate(blocks):
        if i:
            out.append("\\par\\vspace{6pt}")
        out += b
    if note:
        out.append("\\par\\vspace{2pt}\\tabfoot{%s}" % note)
    out.append("\\endgroup\\par\\addvspace{8pt}")
    return "\n".join(out) + "\n"


def group(text, ncols):
    return "\\multicolumn{%d}{l}{\\textit{%s}}" % (ncols, text)


