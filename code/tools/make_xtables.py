def used_keys(tex):
    body = "\n".join(l for l in tex.splitlines() if not l.startswith("%"))
    return sorted(set(XRES.findall(body))), sorted(set(RES.findall(body)))


def known_res_keys(paper_dir):
    p = os.path.join(paper_dir, "results_macros.tex")
    if not os.path.exists(p):
        return None
    txt = open(p, encoding="utf-8", errors="replace").read()
    return set(re.findall(r"csname resv@(.+?)\\endcsname", txt))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--results", default=os.path.join(REPO, "results"))
    ap.add_argument("--out", default=os.path.join(REPO, "paper", "tables"))
    ap.add_argument("--paper", default=os.path.join(REPO, "paper"))
    ap.add_argument("--allow-missing", action="store_true")
    a = ap.parse_args(argv)
    ctx = X.build_all(a.results, a.allow_missing)
    if ctx.scope_errors:
        sys.stderr.write("make_xtables: WRONG SCOPE\n  " + "\n  ".join(ctx.scope_errors) + "\n")
        return 4
    if ctx.errors and not a.allow_missing:
        sys.stderr.write("make_xtables: sources missing:\n  " + "\n  ".join(sorted(set(ctx.errors))[:20]) + "\n")
        return 3
    res_keys = known_res_keys(a.paper)
    bad = []
    os.makedirs(a.out, exist_ok=True)
    for fn, fnc in TABLES:
        if fn == "tab_pf.tex" and "pf" in ctx.absent:
            print("make_xtables: tab_pf.tex skipped (results/pf/pf_summary.json absent)")
            continue
        tex = fnc(ctx.entries)
        xk, rk = used_keys(tex)
        miss = [k for k in xk if k not in ctx.entries]
        bad += ["%s: \\xres{%s}" % (fn, k) for k in miss]
        if res_keys is not None:
            bad += ["%s: \\res{%s} (not in paper/results_macros.tex)" % (fn, k) for k in rk if k not in res_keys and not any(k == r2 for r2 in res_keys)]
        if (miss or bad) and not a.allow_missing:
            continue
        with open(os.path.join(a.out, fn), "w", encoding="utf-8") as f:
            f.write(tex)
        print("make_xtables: %s (%d \\xres keys, %d \\res keys)" % (fn, len(xk), len(rk)))
    if bad:
        sys.stderr.write("make_xtables: keys without a source:\n  " + "\n  ".join(bad) + "\n")
        if not a.allow_missing:
            return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
