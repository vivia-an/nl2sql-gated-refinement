#!/usr/bin/env python3
# usage: python3 code/tools/gen_tab_s_steps.py paper/supp_text/tab_s_steps.tex
# generates paper/supp_text/tab_s_steps.tex: evidence and price of every step, both cost bases (S17.15)
import sys
OUT = sys.argv[1]
N = {"zs": "single call", "zsretry": "single call + retry", "zsretryempty": "empty-gate retry",
     "zsthink": "thinking on", "macsql": "MAC-SQL", "gated": "pipeline", "fixed": "fixed loop", "gatedempty": "pipeline + empty gate"}
Q = [("zsretry", "zs"), ("zsretryempty", "zs"), ("zsretryempty", "zsretry"), ("zsthink", "zs"), ("macsql", "zs"),
     ("gated", "zs"), ("gated", "zsretry"), ("gated", "zsretryempty"), ("gated", "zsthink"), ("gated", "macsql"),
     ("gatedempty", "zs"), ("gatedempty", "gated"), ("gatedempty", "zsretryempty"),
     ("fixed", "zs"), ("fixed", "zsretry"), ("fixed", "gated"), ("fixed", "gatedempty")]
DS = [s for s in Q if "zsthink" not in s and "macsql" not in s]
BK = [("plus", "Qwen3.7-Plus", Q), ("flash", "Qwen3.7-Flash", Q), ("27b", "Qwen3.5-27B", Q), ("ds", "Non-Qwen model (deepseek-v4.1-flash-1017)", DS)]

def row(b, x, y):
    k = "X2DS.%s.w7.%s_over_%s" % (b, x, y)
    r = lambda s: "\\xres{%s.%s}" % (k, s)
    nol = x in ("zsthink", "macsql") or y in ("zsthink", "macsql")   # arms that were not rerun: no reading line
    return ("%s vs.\\ %s & %s %s & %s & %s\\,/\\,%s & %s%s & %s & %s (%s/%s) & %s\\,/\\,%s & %s\\,/\\,%s (%s)\\\\"
            % (N[x][0].upper() + N[x][1:], N[y], r("dex"), r("dex.ci"), r("p_pos"), "--" if nol else r("line_direct"), "--" if nol else r("line_indep"),
               r("det_s"), "$^{i}$" if nol else "", r("mde"), r("st_dex"), r("st_up"), r("st_down"), r("dcost_disc"), r("dcost_list"),
               r("price_disc"), r("price_list"), r("price_list_best")))

def table(parts, label, cont):
    L = []
    L.append("\\begin{table}[!p]")
    L.append("\\begin{adjustwidth}{-\\extralength}{0cm}")
    cap = ("Every step between two arms: evidence and price, both cost bases (post hoc; \\res{setup.bird_dev.n_questions} questions, one run per cell%s)."
           % ("; continued from Table~\\ref{tab:s_steps}" if cont else ""))
    L.append("\\caption{%s\\label{%s}}" % (cap, label))
    L.append("\\scriptsize\\setlength{\\tabcolsep}{2pt}")
    L.append("\\begin{tabularx}{\\linewidth}{Y{1.7}Z{1.15}Z{0.3}Z{0.6}Z{0.35}Z{0.35}Z{0.85}Z{0.65}Z{1.05}}")
    L.append("\\toprule")
    L.append("Step & Gain, pp [widest] & $P_{+}$ & Lines & Det. & MDE & Same text (up/down) & Extra CNY disc.\\,/\\,full & CNY per extra correct disc.\\,/\\,full (lowest)\\\\")
    L.append("\\midrule")
    for i, (b, name, steps) in enumerate(parts):
        if i:
            L.append("\\midrule")
        L.append("\\multicolumn{9}{l}{\\textit{%s}}\\\\" % name)
        for x, y in steps:
            L.append(row(b, x, y))
    L.append("\\bottomrule")
    L.append("\\end{tabularx}")
    if not cont:
        L.append("\\tabfoot{Gain: EX of the first arm minus EX of the second, with the widest of the four intervals (an end printed as 0.00 contains 0). "
                 "$P_{+}$: share of database-clustered bootstrap draws with a positive gain (not a probability that the step helps; it ignores run-to-run variation). Lines: reading lines from the reruns, direct / independence formula (Section~\\mref{sec:stats}); "
                 "``--'' where an arm was not rerun (thinking on, MAC-SQL). Det.: the widest interval excludes zero and the gain reaches the line, under both lines (yes), under neither (no), or under one only (line); "
                 "$^{i}$: no line, the interval condition alone (a weaker verdict than a ``yes'' with lines). MDE: minimum detectable effect at 80\\% power, $2.80$ times the database-clustered standard error; it ignores the reading line and the wider intervals, so the detection rule needs more than the MDE where a line exceeds it. "
                 "Same text: the gain when a question with identical final query text in both arms is scored the same in both (re-execution flips near the time limit removed), with the questions right only in the first arm (up) and only in the second (down). "
                 "Extra CNY per 1,000 questions with the cache discount (disc.) and with every prompt token at full price (full). "
                 "CNY per extra correct answer: extra CNY divided by extra correct answers; undefined where the gain is not positive, ``cheaper'' where the first arm also costs less; lowest: the price at the upper end of the widest interval. "
                 "Empty-gate retry: the single call + retry whose gate also fires on an empty result; pipeline + empty gate: the pipeline with the same gate (run W8). Values from \\texttt{results/x2ds/x2ds\\_keys.json} (key family \\texttt{<b>.w7.*}).}")
    L.append("\\end{adjustwidth}")
    L.append("\\end{table}")
    return L

out = ["% generated by code/tools/gen_tab_s_steps.py (2026-10-29): Tables S-steps, every step with both cost bases; replaces the decision-ladder table"]
out += table(BK[:2], "tab:s_steps", False)
out.append("")
out += table(BK[2:], "tab:s_steps2", True)
open(OUT, "w").write("\n".join(out) + "\n")
