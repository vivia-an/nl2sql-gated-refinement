def tab_primary(keys):
    """Amendment 3 family: H1 = P1', H2 = W1, H3 = P3, H4 = P5' (confirmatory); P2 and P4 secondary.
    Every key below is the name the paper uses; make_macros.OVERRIDES redirects P1.* -> P1prime.*, P3.p_adj|verdict -> Pstar.P3.*, P5.* -> P5prime.*, P2/P4 p_adj|verdict -> the
    S-A / S-E values and P.family.* -> Pstar.family.*, so the table shows family P* (SAP 15.3). The row exists when the P* producer (`status_key`) has run."""
    def row(pid, name, desc, probes, second=None, status_key=None, padj=None):
        if not has(keys, status_key or (pid + ".status")):
            return "%s & %s & -- & -- & %s" % (name, desc, PH)
        probe = next((p for p in probes if has(keys, p)), None)
        est = (r(probe) + (" " + r(probe + ".ci") if (probe + ".ci_lo") in keys else "")) if probe else "--"
        if second and has(keys, second):
            est += "; ratio " + r(second) + (" " + r(second + ".ci") if (second + ".ci_lo") in keys else "")
        return "%s & %s & %s & %s & %s" % (name, desc, est, padj or r(pid + ".p_adj"), r(pid + ".verdict"))   # the P* producer ran (status_key), so p_adj / verdict must resolve: make_macros reports them missing otherwise
    rows = [row("P1", "P1$'$", "Cost: gated loop vs fixed loop, mean over backbones; EX non-inferior ($-1.5$ pp) and calls ratio $<0.80$", ["P1.delta_ex"], "P1.calls_ratio", status_key="P1prime.status"),
            row("W1", "W1", "Cheaper backbones: gated pipeline vs single call, mean over the cheaper backbones; EX above zero", ["W1.delta_ex"]),
            row("P3", "P3", "Routing: consistency-augmented score vs V3 on the final answer, $\\Delta$AUROC", ["P3.dauroc"], status_key="Pstar.P3.p_adj", padj="\\xres{RV2.small.pstar.P3.padj_boot}"),   # 0.0008 instead of the '<0.001' print of the p format
            row("P5", "P5$'$", "Repair: repair rate vs error text withheld, pooled over backbones", ["P5.diff_rate_pp"], status_key="P5prime.status"),
            "\\midrule",
            row("P2", "S-A (P2)", "Fixed loop vs the best baseline picked on the development set (B$^\\ast$), which uses fewer calls; EX non-inferior ($-3.0$ pp)", ["P2.delta_ex"], status_key="P2.p_adj_sa"),
            row("P4", "S-E (P4)", "Store: value-weighted vs append-only at 40\\% wrong entries (log-odds; $\\Delta$EX in pp if no interval)", ["P4.logodds", "P4.diff_pp"], status_key="P4.p_adj_se")]
    return float_wrap("tab:primary", "Primary confirmatory family P$^\\ast$ (P1$'$, W1, P3, P5$'$; Holm, family-wise $\\alpha=0.05$; one-sided $p$ doubled) and two secondary tests. Estimate: difference in percentage points (pp; P1$'$, W1, P5$'$, S-A), AUROC (P3) or log-odds (S-E), with its 95\\% database-clustered percentile interval.",
                      [("Y", 0.6), ("Y", 3.0), ("Y", 1.9), ("Z", 0.8), ("Y", 1.2)], "Test & Hypothesis & Estimate [95\\% CI] & Holm-adj.\\ $p$ & Verdict", rows,
                      note="Confirmatory family P$^*$ (SAP Amendment 3): Holm over \\res{P.family.m} tests (P1$'$, W1, P3, P5$'$; dropped: \\res{P.family.dropped}). The adjusted $p$ values are those of the pre-specified percentile bootstrap, which are near its floor; re-tested post hoc with the database as the unit (exact sign-flip, same Holm procedure) the adjusted $p$ of P1$'$, W1 and P3 is \\xres{RV2.small.pstar.P1p.padj_sf}, \\xres{RV2.small.pstar.W1.padj_sf} and \\xres{RV2.small.pstar.P3.padj_sf} (P1$'$ with equal weight per database: \\xres{RV2.small.pstar.P1p.padj_sfu}). P2 and P4 are secondary rows; their Holm-adjusted $p$ is computed inside their own families (S-A, $m=\\res{P2.sa_family_m}$ comparisons of the fixed loop with the re-implemented baselines, Memo-SQL on the 500 questions it ran; S-E, $m=\\res{P4.se_family_m}$).")


def tab_e1(keys):
    rows = []
    for s, name in SYS_NAMES:
        p = "E1.%s.%s" % (s, MODEL)
        if (p + ".status") in keys and not (p + ".ex.mean") in keys:                  # run produced no prediction at all (technical failure): not a 0 % result
            rows.append("%s & \\multicolumn{6}{l}{\\textit{n/a (run failed, to be repeated)}}" % name)
            continue
        if not has(keys, p):
            continue
        d = "E1.vs_zs.%s.%s.delta_ex" % (s, MODEL)
        rows.append(" & ".join([name, cell(keys, p + ".ex"), cell(keys, d) if s != "zs" else "--", cell(keys, p + ".calls", False), cell(keys, p + ".tokens", False),
                                cell(keys, p + ".soft_f1", False), cell(keys, p + ".silent_error", False)]))
    if not rows:
        rows = ["\\multicolumn{7}{l}{%s}" % PH]
    return float_wrap("tab:e1", "Main results on the BIRD development set (\\res{setup.bird_dev.n_questions} questions, backbone \\texttt{qwen3.7-plus}, run r0). EX with 95\\% database-clustered CI; $\\Delta$EX against the single call in percentage points (pp); calls and tokens per question on the answer path. The Memo-SQL row covers a 500-question subset: its EX and $\\Delta$EX (against the single call on the same questions) are not comparable with the rows on all \\res{setup.bird_dev.n_questions} questions.",
                      [("Y", 1.7), ("Z", 1.5), ("Z", 1.7), ("Z", 0.9), ("Z", 1.0), ("Z", 0.9), ("Z", 1.0)],
                      "System & EX (\\%) [CI] & $\\Delta$EX (pp) [CI] & Calls per question & Tokens per question & Soft-F1 (\\%) & Silent errors (\\%)", rows,
                      note="Published numbers of systems that were not re-run are in \\STpub{}, not here.")


def tab_ablation(keys):
    rows = []
    cfgs = [("full_gated", "Gated loop (base of the ablations)"), ("abl_m1", "$-$M1 (no task graph)"), ("abl_m2", "$-$M2"), ("abl_m3", "$-$M3 (dense only)"), ("abl_m3force", "M3 forced routing"),
            ("abl_m5", "$-$M5 (root only)"), ("abl_m6", "$-$M6"), ("abl_q", "$-$Q (legacy identifier rendering)")]
    for c, name in cfgs:
        p = "E3.%s" % c
        if not has(keys, p):
            continue
        rows.append(" & ".join([name, cell(keys, p + ".ex"), cell(keys, p + ".delta_vs_full.delta_ex"), r(p + ".delta_vs_full.p_adj") if has(keys, p + ".delta_vs_full.p_adj") else "--"]))
    if not rows:
        rows = ["\\multicolumn{4}{l}{%s}" % PH]
    return float_wrap("tab:ablation", "Ablations of the gated loop (the base the ablation arms were run on) on the strongest backbone (development set, r0). $\\Delta$EX is the ablated configuration minus the gated loop, in percentage points (pp); exact McNemar tests, Holm-adjusted.",
                      [("Y", 2.4), ("Z", 1.4), ("Z", 1.6), ("Z", 1.0)], "Configuration & EX (\\%) [CI] & $\\Delta$EX (pp) [CI] & Holm-adj.\\ $p$", rows,
                      note="Cochran's $Q$ over all configurations: \\res{E3.cochran.q} (df \\res{E3.cochran.df}, $p$ = \\res{E3.cochran.p})." if has(keys, "E3.cochran.q") else None)


def tab_backbone(keys):
    models = sorted({k.split(".")[1] for k in keys if k.startswith("E2.") and k.endswith(".gain_gated_vs_zs.delta_ex.mean")})
    rows = []
    for m in models:
        rows.append(" & ".join([esc(m), cell(keys, "E2.%s.zs.ex" % m), cell(keys, "E2.%s.full_gated.ex" % m), cell(keys, "E2.%s.gain_gated_vs_zs.delta_ex" % m),
                                cell(keys, "E2.%s.full_gated.calls" % m, False)]))
    if not rows:
        rows = ["\\multicolumn{5}{l}{%s}" % PH]
    return float_wrap("tab:backbone", "Backbone dependence (development set, r0). Gain = EX of the gated pipeline $-$ EX of the single call, in percentage points (pp).",
                      [("Y", 1.5), ("Z", 1.5), ("Z", 1.5), ("Z", 1.7), ("Z", 1.0)],
                      "Backbone & Single call EX (\\%) [CI] & Gated pipeline EX (\\%) [CI] & Gain (pp) [CI] & Calls per question", rows,
                      note="Spearman correlation of gain with single-call EX across backbones: \\res{E2.gain_vs_zs_ex.spearman} (descriptive)." if has(keys, "E2.gain_vs_zs_ex.spearman") else None)


