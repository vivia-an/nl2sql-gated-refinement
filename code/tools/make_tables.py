def tab_taxonomy(keys):
    systems = sorted({k.split(".")[2] for k in keys if k.startswith("E10.llm.") and k.endswith(".prevalence.mean")})
    if not systems:
        return float_wrap("tab:taxonomy", "Error classes of failed answers from the LLM annotation (two independent runs of Claude Sonnet 5.5, adjudicated by a third).", [("Y", 3.0), ("Z", 2.0)], "Class & Prevalence (\\%) [CI]", ["\\multicolumn{2}{l}{%s}" % PH])
    rows = []
    for c, name in L_NAMES:
        cells = [cell(keys, "E10.llm.%s.%s.prevalence" % (s, c)) for s in systems]
        rows.append(" & ".join(["%s %s" % (c, name)] + cells))
    return float_wrap("tab:taxonomy", "Error classes of failed answers, stratum-weighted prevalence (\\%) with stratified-bootstrap 95\\% CI. Labels are model-assigned (two independent Claude Sonnet 5.5 runs, adjudicated by a third); all prevalences are exploratory.",
                      [("Y", 2.2)] + [("Z", 1.5)] * len(systems), "Class & " + " & ".join(esc(s) for s in systems), rows,
                      note="Agreement between the two annotation runs: Cohen's $\\kappa$ \\res{E10.kappa} \\res{E10.kappa.ci}; Gwet's AC1 \\res{E10.ac1}. Agreement of one model with itself measures consistency, not validity.")


def tab_rootstatus(keys):
    rows = []
    for lab, name in [("full_fixed", "Fixed loop"), ("full_gated", "Gated loop")]:
        for st, sn in [("err", "execution failure"), ("empty", "empty result"), ("nonempty", "non-empty result")]:
            p = "E1.rootstatus.%s.%s" % (lab, st)
            if has(keys, p):
                rows.append(" & ".join([name, sn, r(p + ".n"), r(p + ".ex_root") if has(keys, p + ".ex_root") else "--", r(p + ".ex_final") if has(keys, p + ".ex_final") else "--",
                                        r(p + ".gain") if has(keys, p + ".gain") else "--", r(p + ".harm") if has(keys, p + ".harm") else "--"]))
    if not rows:
        rows = ["\\multicolumn{7}{l}{%s}" % PH]
    return float_wrap("tab:rootstatus", "Execution accuracy by the status of the first (root) candidate, before and after the loop. Gain = questions wrong at the root and right at the end; harm = the reverse (numbers of questions).",
                      [("Y", 1.2), ("Y", 1.5), ("Z", 0.8), ("Z", 1.0), ("Z", 1.0), ("Z", 0.8), ("Z", 0.8)], "System & Root status & $n$ & EX at root (\\%) & EX at end (\\%) & Gain (questions) & Harm (questions)", rows)


TABLES = [("tab_primary", tab_primary), ("tab_e1", tab_e1), ("tab_ablation", tab_ablation), ("tab_backbone", tab_backbone), ("tab_routing", tab_routing),
          ("tab_pollution", tab_pollution), ("tab_taxonomy", tab_taxonomy), ("tab_rootstatus", tab_rootstatus)]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--results", default=os.path.join(REPO, "results"))
    ap.add_argument("--out", default=os.path.join(REPO, "paper", "tables"))
    ap.add_argument("--ref", action="store_true", help="REFERENCE build: read results/ref (scope tuning-reference), write paper/ref/tables")
    ap.add_argument("--preview", action="store_true", help="accept synthetic results; --out must then be below a directory starting with '_' (layout checks only)")
    a = ap.parse_args(argv)
    if a.ref:
        if a.results == os.path.join(REPO, "results"):
            a.results = os.path.join(REPO, "results", "ref")
        if a.out == os.path.join(REPO, "paper", "tables"):
            a.out = os.path.join(REPO, "paper", "ref", "tables")
    if a.preview and not any(x.startswith("_") for x in os.path.abspath(a.out).split(os.sep)):
        sys.exit("make_tables: --preview output must go below a directory whose name starts with '_' (e.g. paper/_preview/tables)")
    keys = load(a.results, a.preview, a.ref)
    os.makedirs(a.out, exist_ok=True)
    for stem, fn in TABLES:
        p = os.path.join(a.out, stem + ".tex")
        with open(p, "w", encoding="utf-8") as f:
            f.write(fn(keys))
        print("make_tables: wrote", p)
    print("make_tables: tables use \\usepackage{tabularx,booktabs,float}; add \\input{tables/<name>} where a table is placed; run make_macros.py afterwards (it scans paper/tables).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
