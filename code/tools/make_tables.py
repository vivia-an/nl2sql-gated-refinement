#!/usr/bin/env python3
"""results/*.json -> paper/tables/*.tex   (stdlib only, Python 3.6; runs on the host)

    python3 code/tools/make_tables.py [--results results] [--out paper/tables] [--show-missing]
    python3 code/tools/make_tables.py --ref        # REFERENCE build: results/ref (scope tuning-reference) -> paper/ref/tables (never paper/tables)

Every number in a generated table is a \\res{KEY} reference (CONTRACT 0): this script never prints a value from the json files, it only decides which
rows exist (a row is written when its system / configuration has at least one key in results/, otherwise a 'not run' row is written so that the
table states what is missing). `make_macros.py` scans paper/tables/*.tex, so keys a table needs and results/ cannot yet provide are reported there.
Tables (file -> source): tab_primary (primary.json P1-P5), tab_e1 (E1: main results, cost), tab_ablation (E3), tab_backbone (E2), tab_routing (E7),
tab_pollution (E4), tab_taxonomy (E10 LLM annotation), tab_rootstatus (E1 root status).
Files are written as bare tabular environments inside `table` floats; captions/labels carry the table numbers of docs/STORYLINE R10."""
import argparse
import glob
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MODEL = "qwen37plus"
SYS_NAMES = [("zs", "Single call"), ("dail", "DAIL-style"), ("sdebug", "Self-Debug"), ("macsql", "MAC-SQL"), ("acsql_s", "AC-SQL"), ("acsql_x", "AC-SQL (extended)"),
             ("memosql", "Memo-SQL (subset)"), ("bon_vote", "BoN + execution vote"), ("sc_cot", "SC-CoT"), ("bon_critic", "BoN + Critic"),
             ("full_fixed", "Fixed loop"), ("full_gated", "Gated loop")]
L_NAMES = [("L1", "schema linking"), ("L2", "join path"), ("L3", "filter / value"), ("L4", "aggregation / grouping / ordering"), ("L5", "wrong criterion (exploratory)"),
           ("L6", "reference query suspect"), ("L7", "ambiguous question"), ("L8", "other")]
PH = "\\textit{not run}"


def load(results_dir, preview=False, ref=False):
    keys = set()
    for f in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        if os.path.basename(f).startswith("_"):
            continue
        d = json.load(open(f))
        scope = (d.get("_meta") or {}).get("scope", "confirmatory")
        if ref:
            if scope != "tuning-reference":
                sys.exit("make_tables --ref: %s has scope %r; the reference build reads only scope 'tuning-reference' (results/ref)" % (f, scope))
        elif scope == "tuning-reference":
            sys.exit("make_tables: %s has scope 'tuning-reference'; reference values never enter paper/tables (use --ref)" % f)
        if not ref and scope not in (("confirmatory", "tuning-export", "synthetic") if preview else ("confirmatory", "tuning-export")):
            sys.exit("make_tables: %s has scope %r - tables for the paper are built from confirmatory results only" % (f, scope))
        keys.update(k for k in d if not k.startswith("_"))
    return keys


def has(keys, prefix):
    return any(k == prefix or k.startswith(prefix + ".") for k in keys)


def r(k):
    return "\\res{%s}" % k


def cell(keys, k, ci=True):
    """value (+ CI) cell for key k (k.mean / k.ci are derived by make_macros)."""
    ci_ok = ci and ((k + ".ci_lo") in keys or (k + ".ci") in keys or (k + ".mean_ci_lo") in keys)
    return (r(k) + (" " + r(k + ".ci") if ci_ok else "")) if has(keys, k) else "--"


def esc(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def colspec(cols):
    """cols = [(kind, weight)], kind in Y (left, wrapping), Z (right), C (centred); weights are relative.
    tabularx scales the X columns so that the table is exactly \linewidth wide whatever the cell content is (a [KEY] fallback or a number),
    so replacing macros by results does not change the layout (N4)."""
    tot = float(sum(w for _, w in cols))
    return "".join("%s{%.3f}" % (k, w * len(cols) / tot) for k, w in cols)


def float_wrap(label, caption, cols, header, rows, note=None, small=True):
    out = ["% GENERATED by code/tools/make_tables.py from results/*.json -- do not edit", "\\begin{table}[!htb]", "\\caption{%s}\\label{%s}" % (caption, label), "\\centering"]
    if small:
        out.append("\\footnotesize")
    out.append("\\begin{tabularx}{\\linewidth}{%s}" % colspec(cols))
    out += ["\\toprule", header + " \\\\", "\\midrule"]
    out += [x + " \\\\" if not x.startswith("\\midrule") else x for x in rows]
    out += ["\\bottomrule", "\\end{tabularx}"]
    if note:
        out.append("\\tabfoot{%s}" % note)
    out.append("\\end{table}")
    return "\n".join(out) + "\n"


